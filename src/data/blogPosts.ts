export function getPublishedPosts(): BlogPost[] {
  const today = new Date().toISOString().split('T')[0];
  return blogPosts
    .filter((p) => p.status === 'published' && p.published_date <= today)
    .sort((a, b) => b.published_date.localeCompare(a.published_date));
}

export function getPostBySlug(slug: string): BlogPost | undefined {
  const today = new Date().toISOString().split('T')[0];
  return blogPosts.find(
    (p) => p.slug === slug && p.status === 'published' && p.published_date <= today
  );
}

export function getRelatedPosts(currentId: string, category?: string, location?: string): BlogPost[] {
  const today = new Date().toISOString().split('T')[0];
  const published = blogPosts.filter(
    (p) => p.status === 'published' && p.published_date <= today && p.id !== currentId
  );

  if (category) {
    const byCat = published.filter((p) => p.category === category);
    if (byCat.length > 0) return byCat.slice(0, 3);
  }

  if (location) {
    const byLoc = published.filter((p) => p.location === location);
    if (byLoc.length > 0) return byLoc.slice(0, 3);
  }

  return published.slice(0, 3);
}
